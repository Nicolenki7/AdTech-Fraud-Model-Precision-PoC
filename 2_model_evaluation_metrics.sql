--  SET CONTEXT ()
USE ROLE SYSADMIN;
USE WAREHOUSE FRAUD_ANALYSIS_WH;
USE DATABASE FRAUD_DETECTION_DB; -- Ensures we look in the right DB
USE SCHEMA RAW_LOGS;             -- Ensures we look in the right Schema

-- RE-RUN THE ANALYSIS (Step 2 Logic)
CREATE OR REPLACE TABLE MODEL_PERFORMANCE_ANALYSIS AS
SELECT
    IP_ADDRESS,
    TOTAL_CLICKS,
    USER_TYPE,
    IS_ACTUALLY_BOT,
    -- Prediction Logic
    CASE 
        WHEN TOTAL_CLICKS > 50 THEN TRUE 
        ELSE FALSE 
    END AS PREDICTED_AS_BOT,
    -- Confusion Matrix Logic
    CASE
        WHEN (TOTAL_CLICKS > 50) AND (IS_ACTUALLY_BOT = TRUE) THEN 'TRUE_POSITIVE'
        WHEN (TOTAL_CLICKS <= 50) AND (IS_ACTUALLY_BOT = FALSE) THEN 'TRUE_NEGATIVE'
        WHEN (TOTAL_CLICKS > 50) AND (IS_ACTUALLY_BOT = FALSE) THEN 'FALSE_POSITIVE'
        WHEN (TOTAL_CLICKS <= 50) AND (IS_ACTUALLY_BOT = TRUE) THEN 'FALSE_NEGATIVE'
    END AS EVALUATION_CATEGORY
FROM TRAFFIC_EVALUATION;

--  AGGREGATE METRICS (Step 3 Logic)
SELECT
    EVALUATION_CATEGORY,
    COUNT(*) AS IP_COUNT,
    -- Business Interpretation
    CASE 
        WHEN EVALUATION_CATEGORY = 'FALSE_POSITIVE' THEN 'Lost Revenue / Angry Users'
        WHEN EVALUATION_CATEGORY = 'FALSE_NEGATIVE' THEN 'Wasted Ad Budget / Fraud Leakage'
        ELSE 'Good Performance'
    END AS BUSINESS_IMPACT
FROM MODEL_PERFORMANCE_ANALYSIS
GROUP BY 1, 3;
